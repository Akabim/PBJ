using System;
using System.Collections.Generic;
using System.Net;
using System.Net.NetworkInformation;
using System.Net.Sockets;
using System.Threading;
using UnityEngine;

namespace PBJ.Networking
{
    // M3 LAN discovery (HOST side): periodically UDP-broadcasts a
    // LanDiscoveryPacket advertising this host's PBJ room (room code, the
    // actual NGO game port, optional host name). LAN ONLY: link-local /
    // subnet broadcast sockets, no relay, no UGS, no internet.
    //
    // All socket work runs on a dedicated background thread; the main thread
    // only starts/stops it and swaps the encoded packet. Stop is clean:
    // a volatile flag ends the loop within one sleep slice, and the socket is
    // disposed by the thread itself (using-block), so no leaked sockets or
    // orphaned threads on scene exit / OnDestroy.
    //
    // Integration note (for a later agent): call StartBroadcasting(...) after
    // NetworkSession.StartHost() succeeds, passing the SAME port NetworkSession
    // advertises (UnityTransport). Multiple PBJ hosts on one LAN are fine -
    // each advertises its own code/port from its own ephemeral source port.
    public class LanRoomBroadcaster : MonoBehaviour
    {
        [Header("LAN Discovery (UDP broadcast)")]
        [Tooltip("UDP port PBJ clients listen on for discovery announcements.")]
        [SerializeField] private int discoveryPort = LanDiscoveryPacket.DefaultDiscoveryPort;

        [Tooltip("Actual NGO game port clients should connect to (must match NetworkSession/UnityTransport).")]
        [SerializeField] private ushort gamePort = 7777;

        [Tooltip("Optional human-readable host name advertised with the room.")]
        [SerializeField] private string hostName = "";

        [Tooltip("Seconds between advertisement packets.")]
        [SerializeField] private float broadcastIntervalSeconds = 1.0f;

        private Thread _worker;
        private volatile bool _stopRequested;
        private volatile byte[] _packet;        // encoded once per configuration; read by the thread
        private volatile string _roomCode = ""; // code actually being advertised
        private volatile float _intervalMs = 1000f;
        private List<IPAddress> _broadcastTargets;
        private int _lastErrorLogTickCount = int.MinValue; // throttles socket error spam

        public bool IsBroadcasting => _worker != null && _worker.IsAlive && !_stopRequested;

        // Room code currently advertised (empty when not broadcasting).
        public string CurrentRoomCode => _roomCode;

        // Convenience overload using the serialized defaults; the room code is
        // auto-generated by the host when the serialized one is empty.
        public bool StartBroadcasting()
        {
            return StartBroadcasting(null, gamePort, hostName);
        }

        // Starts (or reconfigures while running) the advertisement. A null /
        // empty roomCode is generated by the host via RoomCode.Generate().
        // Returns false on invalid configuration (nothing is started then).
        public bool StartBroadcasting(string roomCode, ushort gamePort, string hostName = null)
        {
            if (roomCode == null || roomCode.Length == 0)
            {
                roomCode = RoomCode.Generate(); // host generates the code
            }
            if (!RoomCode.IsValid(roomCode))
            {
                LogError($"Invalid room code '{roomCode}' - broadcasting not started");
                return false;
            }
            if (gamePort == 0)
            {
                LogError("Invalid game port 0 - broadcasting not started");
                return false;
            }
            if (discoveryPort < 1 || discoveryPort > 65535)
            {
                LogError($"Invalid discovery port {discoveryPort} - broadcasting not started");
                return false;
            }

            string advertisedHostName = hostName ?? this.hostName;
            if (!LanDiscoveryPacket.TryEncode(roomCode, gamePort, advertisedHostName, out byte[] packet))
            {
                LogError("Failed to encode discovery packet - broadcasting not started");
                return false;
            }

            _roomCode = roomCode;
            _packet = packet; // volatile swap: a running thread picks it up next tick
            _intervalMs = Mathf.Clamp(broadcastIntervalSeconds, 0.1f, 30f) * 1000f;

            if (_worker == null || !_worker.IsAlive)
            {
                _broadcastTargets = BuildBroadcastTargets();
                _stopRequested = false;
                _worker = new Thread(RunBroadcastLoop)
                {
                    IsBackground = true, // never blocks app shutdown
                    Name = "PBJ.LanRoomBroadcaster"
                };
                _worker.Start();
                Log($"Broadcasting room {roomCode} (game port {gamePort}) on UDP {discoveryPort}");
            }
            return true;
        }

        // Stops the background thread and waits briefly for a clean exit.
        // Safe to call multiple times; also invoked from OnDisable/OnDestroy.
        public void StopBroadcasting()
        {
            _stopRequested = true;
            var worker = _worker;
            _worker = null;
            if (worker != null && worker.IsAlive && !worker.Join(2000))
            {
                LogError("LAN broadcaster thread did not stop within 2s (thread is background; it will die with the app)");
            }
            _packet = null;
            _roomCode = "";
        }

        // Background-thread body: sends the currently advertised packet to
        // every LAN broadcast target once per interval. The socket is created
        // and disposed entirely inside this thread (using-block), so stop is
        // clean even if the main thread never gets a chance to help. The
        // interval is slept in small slices so the volatile stop flag is
        // observed within one slice; a null packet (stop in progress or no
        // configuration yet) idles briefly instead of sending.
        private void RunBroadcastLoop()
        {
            const int SleepSliceMs = 50;

            using (var client = new UdpClient()) // send-only socket, ephemeral source port
            {
                client.EnableBroadcast = true; // required for 255.255.255.255 and directed broadcasts

                while (!_stopRequested)
                {
                    byte[] packet = _packet; // volatile snapshot: swaps are picked up next tick
                    if (packet == null)
                    {
                        Thread.Sleep(SleepSliceMs);
                        continue;
                    }

                    List<IPAddress> targets = _broadcastTargets;
                    if (targets == null || targets.Count == 0)
                    {
                        // No usable targets computed: fall back to the global
                        // LAN broadcast address so advertising still works.
                        targets = DefaultBroadcastTargets;
                    }

                    try
                    {
                        var destination = new IPEndPoint(IPAddress.Any, discoveryPort);
                        foreach (IPAddress target in targets)
                        {
                            destination.Address = target;
                            // One datagram per target; a failed target does not
                            // abort the remaining ones (e.g. adapters that went
                            // away mid-run are skipped on the next pass).
                            client.Send(packet, packet.Length, destination);
                        }
                    }
                    catch (SocketException ex)
                    {
                        if (!_stopRequested)
                        {
                            ThrottledLogError($"Broadcast send failed: {ex.SocketErrorCode}");
                        }
                    }
                    catch (ObjectDisposedException)
                    {
                        break; // socket torn down (shutdown path); exit immediately
                    }
                    catch (Exception ex) // never let the worker thread die unhandled
                    {
                        if (!_stopRequested)
                        {
                            ThrottledLogError($"Broadcast failed: {ex.Message}");
                        }
                    }

                    // Sleep the interval in slices so stop is responsive.
                    int remainingMs = (int)_intervalMs;
                    while (remainingMs > 0 && !_stopRequested)
                    {
                        int sliceMs = Mathf.Min(remainingMs, SleepSliceMs);
                        Thread.Sleep(sliceMs);
                        remainingMs -= sliceMs;
                    }
                }
            }
        }

        // LAN-only broadcast targets: one subnet-directed broadcast address
        // per active non-loopback IPv4 adapter, deduplicated. Directed
        // broadcasts reach hosts on the local subnet even where the global
        // address is filtered; no relay, no UGS, nothing leaves the
        // link-local/subnet scope.
        private static List<IPAddress> BuildBroadcastTargets()
        {
            var targets = new List<IPAddress>();
            try
            {
                foreach (NetworkInterface nic in NetworkInterface.GetAllNetworkInterfaces())
                {
                    if (nic.NetworkInterfaceType == NetworkInterfaceType.Loopback ||
                        nic.OperationalStatus != OperationalStatus.Up)
                    {
                        continue;
                    }

                    foreach (UnicastIPAddressInformation unicast in nic.GetIPProperties().UnicastAddresses)
                    {
                        if (unicast.Address.AddressFamily != AddressFamily.InterNetwork ||
                            unicast.IPv4Mask == null)
                        {
                            continue;
                        }

                        uint ip = ToNetworkUInt(unicast.Address);
                        uint mask = ToNetworkUInt(unicast.IPv4Mask);
                        uint broadcast = ip | ~mask; // host bits set = directed broadcast
                        var address = new IPAddress(new[]
                        {
                            (byte)(broadcast >> 24),
                            (byte)(broadcast >> 16),
                            (byte)(broadcast >> 8),
                            (byte)broadcast
                        });

                        if (!targets.Contains(address))
                        {
                            targets.Add(address);
                        }
                    }
                }
            }
            catch (Exception ex)
            {
                Log($"Could not enumerate network adapters ({ex.Message}); using global broadcast only");
            }

            return targets;
        }

        // IPv4 octets as a big-endian uint so bitwise IP/mask math is correct.
        private static uint ToNetworkUInt(IPAddress address)
        {
            byte[] bytes = address.GetAddressBytes();
            return (uint)((bytes[0] << 24) | (bytes[1] << 16) | (bytes[2] << 8) | bytes[3]);
        }

        // Fallback target list when no adapter broadcast could be computed.
        private static List<IPAddress> DefaultBroadcastTargets { get; } =
            new List<IPAddress> { IPAddress.Broadcast };

        private static void Log(string message)
        {
            Debug.Log($"[PBJ.LanRoomBroadcaster] {message}");
        }

        private static void LogError(string message)
        {
            Debug.LogError($"[PBJ.LanRoomBroadcaster] {message}");
        }

        // Socket errors can repeat every interval; throttle to one log per
        // few seconds so the console is not flooded on a flaky adapter.
        private void ThrottledLogError(string message)
        {
            const int ErrorLogThrottleMs = 5000;
            int now = Environment.TickCount;
            if (_lastErrorLogTickCount == int.MinValue || now - _lastErrorLogTickCount >= ErrorLogThrottleMs)
            {
                _lastErrorLogTickCount = now;
                LogError($"{message} (throttled)");
            }
        }

        private void OnDisable()
        {
            StopBroadcasting();
        }

        private void OnDestroy()
        {
            StopBroadcasting();
        }
    }
}
